/* =====================================================================
 * 自动同步：顶层 slots 恒等于「当前生效版」的 slots。
 * 放在文件末尾而非手写副本——手写两份必然漂移（改了 versions 忘了改顶层，
 * 或反之），而主站 4 处消费方读的是顶层字段，静默漂移会直接让首页
 * 显示与时间表页对不上，且很难被发现。
 * ===================================================================== */
(function syncCurrentVersion(D) {
  if (!D || !Array.isArray(D.versions) || !D.versions.length) return;
  // 以 currentVersionId 为准找当前版；找不到就用 versions[0]
  let cur = null;
  for (const v of D.versions) {
    if (v && v.id === D.currentVersionId) { cur = v; break; }
  }
  if (!cur) cur = D.versions[0];
  // 保证 versions[0] 始终就是当前版：调用方一律读 versions[0]，不必再判断
  const idx = D.versions.indexOf(cur);
  if (idx > 0) D.versions.splice(idx, 1), D.versions.unshift(cur);
  D.slots = D.versions[0].slots || [];
  D.versions.forEach(function (v, i) { v.isCurrent = (i === 0); });
})(window.SCHEDULE_DATA);
