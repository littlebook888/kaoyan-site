-- 补列：tasks.rr_note（滚动复习·任务笔记）—— 2026-10-08 紧急修补
-- -----------------------------------------------------------------------------
-- 报错根因：v1.42.0 新增的笔记字段 rr_note 没写进云端 tasks 表，
--   执行迁移 SQL 时报 `column t.rr_note does not exist`。
--
-- ⚠️ 不补列的隐蔽后果（比报错更麻烦，故务必执行）：
--   store.js 的"缺列自愈"会**自动剥离**云端不存在的列并继续 upsert
--   → 表面上"推送成功"，但 rr_note 根本没进云端：
--      · 笔记只存在这台设备，换设备/清缓存即看不到；
--      · 下次 pullOnce 拉回云端数据（无 rr_note）→ **本地笔记被覆盖消失**，
--        看起来像"笔记自己没了"。
--   这就是 store.js 里那句注释的含义：
--     「已跳过该列继续同步；执行 sql/schema.sql 补齐后该字段才能跨设备同步」
--
-- 执行方式：Supabase 后台 → SQL Editor → 粘贴以下整段 → Run
-- 说明：幂等（IF NOT EXISTS），可重复执行。只需执行本文件，不必重跑迁移文件。
-- =============================================================================

alter table public.tasks add column if not exists rr_note text;

-- ---------- 回读校验：应为 1 行 ----------
select count(*) as rr_note_column_exists
from information_schema.columns
where table_schema = 'public' and table_name = 'tasks' and column_name = 'rr_note';

