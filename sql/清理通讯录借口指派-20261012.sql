-- 清理「今日通讯录名」的借口指派数据（events 表 cx-<date> 行）
-- 生成日期：2026-10-12        版本：v1.43.0
--
-- 背景：
--   「今日通讯录名」功能已于 2026-10-12 下线（用户指定），call.js 不再读写
--   events 表的 cx-<date> 行，其多端同步链路已断开。
--   云端残留 10 行（cx-2026-09-28 … cx-2026-10-10），属于死数据，应当清理。
--
-- ⚠️ 执行纪律（本项目惯例）：**请按 ①→②→③→④ 顺序分段执行，每段执行后核对输出**，
--    不要一次性全选运行。第 ② 段是备份，第 ③ 段才是删除。
--
-- 已完成的留档（执行前请先确认存在）：
--   docs/通话边界-云端数据留档-20261012.json   ← 含这 10 行的完整内容
--   docs/_raw-events-20261012.json             ← events 表全表原始快照
-- ============================================================================


-- ---------------------------------------------------------------------------
-- ① 只读体检：确认要处理哪些行（**不改动任何数据**）
--    期望看到 10 行：2026-09-28(在赶病历) / 09-29(手机快没电) / 09-30(在赶材料)
--                    10-01(家中有事) / 10-02(家中有事) / 10-04(模拟值班)
--                    10-06(手机快没电) / 10-07(在赶病历) / 10-09(急诊在岗)
--                    10-10(模拟跟台手术)
--    注意最后两条带「模拟」字样，是 v1.39.0 之前的开发期占位词残留。
-- ---------------------------------------------------------------------------
select id, date, title, note, time
from events
where id like 'cx-%'
order by date;


-- ---------------------------------------------------------------------------
-- ② 备份：整表拷进归档表（**先删旧表再重建，避免留下空壳**）
--    ⚠️ 不要用 `create table if not exists` —— 已存在时不会拷贝任何数据，
--       会得到一个 0 行的空表，界面数字就此看串（本项目踩过这个坑）。
--    执行后应输出两行且两边的数字相等。
-- ---------------------------------------------------------------------------
drop table if exists events_cx_archive_20261012;

select count(*) as 清理前_events_总行数 from events;

create table events_cx_archive_20261012 as
select * from events;

select (select count(*) from events)                  as events_行数,
       (select count(*) from events_cx_archive_20261012) as 备份表行数;


-- ---------------------------------------------------------------------------
-- ③ 删除：只删 cx- 前缀（通讯录借口指派），**签到 ck-* 与违规 viol-* 一律不动**
-- ---------------------------------------------------------------------------
select count(*) as 本次将删除的行数
from events
where id like 'cx-%';          -- 期望 = 10

delete from events
where id like 'cx-%';


-- ---------------------------------------------------------------------------
-- ④ 复核：确认删除结果 + 其余数据零损失
--    期望三条输出：
--      cx 剩余 = 0
--      ck 签到 = 17（保持不变）
--      viol 违规 = 5（保持不变）
-- ---------------------------------------------------------------------------
select count(*) filter (where id like 'cx-%')   as cx_剩余应为0,
       count(*) filter (where id like 'ck-%')   as ck_签到应为17,
       count(*) filter (where id like 'viol-%') as viol_违规应为5,
       count(*)                                 as events_剩余总行数应为22
from events;

